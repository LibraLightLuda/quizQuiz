import type { Difficulty, KoreanWord, MaskRange } from '../domain/types';

type Seed = readonly [word: string, hint: string, category: string, emoji?: string];

const rangesFor = (word: string, difficulty: Difficulty): MaskRange[] => {
  const length = Array.from(word).length;
  const wanted = difficulty === 'challenge' ? Math.min(3, length - 1) : difficulty === 'hard' ? Math.min(2, length - 1) : difficulty === 'normal' && length >= 4 ? 2 : 1;
  const starts = [...new Set([0, Math.max(0, Math.floor((length - wanted) / 2)), length - wanted])];
  return starts.map((start) => ({ start, length: wanted }));
};

const define = (difficulty: Difficulty, seeds: readonly Seed[]): KoreanWord[] =>
  seeds.map(([word, hintKo, category, emoji], index) => ({
    id: `ko-${difficulty}-${index + 1}`,
    word: word.normalize('NFC'),
    difficulty,
    category,
    hintKo,
    emoji,
    maskRanges: rangesFor(word, difficulty),
    ttsLang: 'ko-KR'
  }));

